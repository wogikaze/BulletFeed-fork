"""Curated seed registry for topic-driven source discovery.

Seeds are identity and ranking hints only. They never schedule fetches,
create subscriptions, or qualify as Claim evidence.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum

from app.services.source_catalog import SourceKind


class DiscoveryProvenance(StrEnum):
    CURATED_SEED = "curated_seed"
    REPOSITORY_METADATA = "repository_metadata"
    WEBSITE_FEED = "website_feed"
    STATUSPAGE_LINK = "statuspage_link"
    SITEMAP_LINK = "sitemap_link"
    PACKAGE_HOMEPAGE = "package_homepage"
    EXTERNAL_INDEX = "external_index"


@dataclass(frozen=True)
class SourceSeed:
    publisher_slug: str
    publisher_name: str
    homepage_url: str
    url: str
    family: SourceKind
    concept_ids: tuple[str, ...]
    provenance: str
    display_name: str
    why: str
    aliases: tuple[str, ...] = ()
    repository: str | None = None
    package: str | None = None


def _seed(
    *,
    slug: str,
    name: str,
    home: str,
    url: str,
    family: SourceKind,
    concepts: tuple[str, ...],
    provenance: str,
    display: str,
    why: str,
    aliases: tuple[str, ...] = (),
    repository: str | None = None,
    package: str | None = None,
) -> SourceSeed:
    return SourceSeed(
        publisher_slug=slug,
        publisher_name=name,
        homepage_url=home,
        url=url,
        family=family,
        concept_ids=concepts,
        provenance=provenance,
        display_name=display,
        why=why,
        aliases=aliases,
        repository=repository,
        package=package,
    )


def _rss_seed(
    *,
    slug: str,
    name: str,
    home: str,
    url: str,
    concepts: tuple[str, ...],
    display: str,
    why: str,
    aliases: tuple[str, ...] = (),
) -> SourceSeed:
    return _seed(
        slug=slug,
        name=name,
        home=home,
        url=url,
        family=SourceKind.RSS_ATOM,
        concepts=concepts,
        provenance=DiscoveryProvenance.WEBSITE_FEED,
        display=display,
        why=why,
        aliases=aliases,
    )


