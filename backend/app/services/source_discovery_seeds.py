_SUBSCRIBE_FEED_FAMILIES = frozenset({SourceKind.RSS_ATOM, SourceKind.JSON_FEED})


def official_subscribe_seeds_for_topic(topic_name: str) -> tuple[SourceSeed, ...]:
    from app.services.user_interest import resolve_concept_id

    concept_id = resolve_concept_id(topic_name)
    return tuple(
        seed
        for seed in (*CURATED_SOURCE_SEEDS, *CURATED_SUBSCRIPTION_FEED_SEEDS)
        if concept_id in seed.concept_ids and seed.family in _SUBSCRIBE_FEED_FAMILIES
    )


def curated_subscribe_feed_urls() -> frozenset[str]:
    from app.services.source_registry import canonicalize_url

    urls: set[str] = set()
    for seed in (*CURATED_SOURCE_SEEDS, *CURATED_SUBSCRIPTION_FEED_SEEDS):
        if seed.family not in _SUBSCRIBE_FEED_FAMILIES:
            continue
        try:
            urls.add(canonicalize_url(seed.url))
        except ValueError:
            continue
    return frozenset(urls)


def is_curated_subscribe_feed_url(url: str) -> bool:
    from app.services.source_registry import canonicalize_url

    try:
        return canonicalize_url(url) in curated_subscribe_feed_urls()
    except ValueError:
        return False

